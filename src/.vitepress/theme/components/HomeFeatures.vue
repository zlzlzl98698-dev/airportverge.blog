            这是因为你的客户端工作在【全局模式 (Global)】，导致原本可以直接连接国内服务器的请求，也绕道香港或日本服务器转了一圈，造成极大的延迟开销。解决方法：在 Clash Verge 或小火箭中，将出站模式切换为【规则模式 (Rule / Config)】，这样国内常用网站直连，仅海外受限网址走专线代理。
